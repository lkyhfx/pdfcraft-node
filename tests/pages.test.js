const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const os = require('node:os')
const api = require(process.env.PDFCRAFT_TEST_PACKAGE || '../npm')
const { pdf } = require('./fixture')
const code = expected => e => e.code === `ERR_PDFCRAFT_${expected}`
async function widths(bytes) { return (await api.getPdfInfo(bytes)).pages.map(p => p.width) }
test('information, ordered merge, selection, duplicates, deletion and replacement', async () => {
  const input = pdf(), info = await api.getPdfInfo(input)
  assert.equal((await api.getPdfInfo(await api.selectPdfPages(pdf({version:'2.0'}),[1]))).version,'2.0')
  assert.equal((await api.getPdfInfo(await api.mergePdfs([pdf({version:'1.4'}),pdf({version:'2.0'})]))).version,'2.0')
  assert.equal((await api.getPdfInfo(await api.replacePdfPages(pdf({version:'1.4'}),pdf({version:'2.0'}),[1]))).version,'2.0')
  assert.equal(info.pageCount, 3); assert.equal(info.version, '1.7')
  assert.equal(info.pages[0].orientation, 'portrait')
  assert.deepEqual(await widths(await api.mergePdfs([input,input])), [200,300,400,200,300,400])
  assert.deepEqual(await widths(await api.selectPdfPages(input,[3,1,3])), [400,200,400])
  assert.deepEqual(await widths(await api.removePdfPages(input,[2,2])), [200,400])
  assert.deepEqual(await widths(await api.replacePdfPages(input,input,[3,1])), [200,300,400,300])
  assert.deepEqual(await widths(await api.replacePdfPages(input,input,[1,2,3])), [200,300,400])
  await assert.rejects(api.selectPdfPages(input,[4]),code('PAGE_RANGE'))
  await assert.rejects(api.selectPdfPages(input,[0]),code('PAGE_RANGE'))
  await assert.rejects(api.selectPdfPages(input,[1.5]),code('PAGE_RANGE'))
  await assert.rejects(api.selectPdfPages(input,[]),code('PAGE_RANGE'))
  await assert.rejects(api.removePdfPages(input,[1,2,3]),code('PAGE_RANGE'))
  await assert.rejects(api.mergePdfs([input,input], { maxInputBytes: input.length }),code('INPUT_TOO_LARGE'))
  await assert.rejects(api.selectPdfPages(pdf({ rich:true }),[1]),code('UNSUPPORTED'))
})
test('split outputs are independent and maintain caller range order', async () => {
  const parts = await api.splitPdf(pdf(),[{start:3,end:3},{start:1,end:2}])
  assert.deepEqual(await widths(parts[0]),[400])
  assert.deepEqual(await widths(parts[1]),[200,300])
  assert.equal((await api.splitPdf(pdf(),[{start:1,end:1}])).length,1)
  await assert.rejects(api.splitPdf(pdf(),[{start:2,end:1}]),code('PAGE_RANGE'))
  await assert.rejects(api.splitPdf(pdf(),[{start:1,end:3}], {maxOutputBytes:1}),code('OUTPUT_TOO_LARGE'))
})
test('file APIs and native batch extraction with recursive limits and cleanup', async () => {
  const dir = await fs.mkdtemp(path.join(os.tmpdir(),'pdfcraft-pages-'))
  try {
    const input = path.join(dir,'input.pdf'), output = path.join(dir,'output.pdf')
    await fs.writeFile(input,pdf())
    assert.equal((await api.getPdfInfoFile(input)).pageCount,3)
    await api.mergePdfFiles([input,input],output)
    assert.equal((await api.getPdfInfoFile(output)).pageCount,6)
    await api.extractPdfPagesFile(input,output,[3,1])
    assert.deepEqual(await widths(await fs.readFile(output)),[400,200])
    const batches = await api.extractPdfRangesFile(input,dir,[{start:1,end:3}],{maxRangePages:2})
    assert.deepEqual(batches.map(b=>[b.start,b.end]),[[1,2],[3,3]])
    for (const b of batches) assert.equal((await fs.stat(b.path)).size,b.bytes)
    const one = await api.splitPdf(pdf(),[{start:1,end:1}])
    const singleBytes = one[0].length
    const sized = await api.extractPdfRangesFile(input,dir,[{start:1,end:3}],{maxBatchBytes:singleBytes+10})
    assert.equal(sized.length,3)
    const before = (await fs.readdir(dir)).sort()
    await assert.rejects(api.extractPdfRangesFile(input,dir,[{start:1,end:3}],{maxBatchBytes:1}),code('OUTPUT_TOO_LARGE'))
    await assert.rejects(api.extractPdfRangesFile(input,dir,[{start:1,end:3}],{maxRangePages:1,maxOutputs:1}),code('OUTPUT_TOO_LARGE'))
    assert.deepEqual((await fs.readdir(dir)).sort(),before)
  } finally { await fs.rm(dir,{recursive:true,force:true}) }
})

test('page crop geometry applies rotation and UserUnit, forms survive duplication', async () => {
  const input=pdf({rotation:90,userUnit:2})
  const info=await api.getPdfInfo(input)
  assert.equal(info.pages[0].rotation,90)
  assert.equal(info.pages[0].width,800)
  assert.equal(info.pages[0].height,400)
  assert.equal(info.pages[0].orientation,'landscape')
  const form=pdf({rich:true,tagged:false})
  assert.deepEqual(await widths(await api.selectPdfPages(form,[1,1,3])),[200,200,400])
})
